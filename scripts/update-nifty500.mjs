// scripts/update-nifty500.mjs
// Rebuilds src/data/nifty500.ts from the official NSE constituent list.
// The index is rebalanced twice a year (March and September); run this then.
//
//   1. Download https://nsearchives.nseindia.com/content/indices/ind_nifty500list.csv
//   2. node scripts/update-nifty500.mjs path/to/ind_nifty500list.csv
//
// No key, no cost. End users never run this.

import { readFileSync, writeFileSync } from 'node:fs'

// NSE industry names → the sector names the screener already uses for US stocks.
const SECTOR = {
  'Financial Services': 'Financials',
  'Information Technology': 'Technology',
  'Healthcare': 'Health Care',
  'Fast Moving Consumer Goods': 'Consumer Staples',
  'Automobile and Auto Components': 'Consumer Discretionary',
  'Consumer Durables': 'Consumer Discretionary',
  'Consumer Services': 'Consumer Discretionary',
  'Textiles': 'Consumer Discretionary',
  'Oil Gas & Consumable Fuels': 'Energy',
  'Power': 'Utilities',
  'Metals & Mining': 'Materials',
  'Chemicals': 'Materials',
  'Construction Materials': 'Materials',
  'Forest Materials': 'Materials',
  'Capital Goods': 'Industrials',
  'Construction': 'Industrials',
  'Services': 'Industrials',
  'Diversified': 'Industrials',
  'Telecommunication': 'Communication',
  'Media Entertainment & Publication': 'Communication',
  'Realty': 'Real Estate',
}

const file = process.argv[2]
if (!file) { console.error('usage: node scripts/update-nifty500.mjs <ind_nifty500list.csv>'); process.exit(1) }

const rows = []
for (const line of readFileSync(file, 'utf8').split(/\r?\n/).slice(1)) {
  // Company Name,Industry,Symbol,Series,ISIN Code  (no quoted commas in this file)
  const [name, industry, symbol] = line.split(',').map(s => s?.trim())
  if (!name || !symbol) continue
  if (!/^[A-Z0-9&\-]{1,20}$/.test(symbol)) { console.warn('skipped odd symbol:', symbol); continue }
  if (!SECTOR[industry]) console.warn('unmapped industry:', industry)
  rows.push([symbol, name.replace(/\s+(Ltd|Limited)\.?$/i, '').replace(/\s+/g, ' '), SECTOR[industry] ?? 'Other'])
}
if (rows.length < 450) { console.error(`only ${rows.length} rows parsed; refusing to write`); process.exit(1) }

const out = `// src/data/nifty500.ts
// Nifty 500 constituents: [NSE symbol, company, sector].
// GENERATED by scripts/update-nifty500.mjs from the public NSE constituent list
// (ind_nifty500list.csv). Do not edit by hand; re-run the script after each
// index rebalance (March and September).
// Generated: ${new Date().toISOString().slice(0, 10)} · ${rows.length} companies

export const NIFTY500: ReadonlyArray<readonly [string, string, string]> = [
${rows.map(r => `  ${JSON.stringify(r)},`).join('\n')}
]
`
writeFileSync(new URL('../src/data/nifty500.ts', import.meta.url), out)
console.log(`wrote ${rows.length} companies`)
